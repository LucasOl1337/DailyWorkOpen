const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const {chromium}=require('playwright-core')
test('Vite: API v1 e controle do Editor pelo websocket', {skip:process.env.DAILYWORK_E2E!=='1',timeout:60000},async t=>{
 const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'dailywork-api-dev-'))
 Object.assign(process.env,{DAILYWORK_DATA_DIR:path.join(tmp,'data'),DAILYWORK_SESSOES_DIR:path.join(tmp,'sessoes'),DAILYWORK_USER_DATA_DIR:path.join(tmp,'userData'),LUCAS_KNOWLEDGE_DIR:path.join(tmp,'knowledge'),DAILYWORK_CAPTURE_PATH:path.join(tmp,'capture.png')})
 const {createServer}=await import('vite')
 const server=await createServer({root:path.resolve(__dirname,'..'),configFile:path.resolve(__dirname,'../vite.config.ts'),server:{host:'127.0.0.1',port:0},logLevel:'silent'})
 await server.listen();t.after(()=>server.close())
 const {baseUrl,token}=JSON.parse(fs.readFileSync(path.join(tmp,'userData/api-dev.json'),'utf8'))
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_BIN||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});t.after(()=>browser.close())
 const page=await browser.newPage()
 const call=async(rota,body)=>{const r=await fetch(baseUrl+rota,{headers:{Authorization:`Bearer ${token}`,...(body?{'Content-Type':'application/json'}:{})},...(body?{method:'POST',body:JSON.stringify(body)}:{})});const json=await r.json();assert.equal(r.status,200,JSON.stringify(json));return json.data}
 await page.goto(baseUrl+'/?view=principal')
 for(let i=0;i<200;i++){const r=await fetch(baseUrl+'/api/v1/interface/estado',{headers:{Authorization:`Bearer ${token}`}});if(r.ok)break;await new Promise(r=>setTimeout(r,50))}
 await call('/api/v1/operacoes/sessoes/criar',{args:['dev-api']})
 await call('/api/v1/interface/navegar',{view:'sessao:dev-api'})
 const state=await call('/api/v1/canvas/estado?alvo=sessao:dev-api')
 await call('/api/v1/canvas/comandos',{alvo:state.alvo,revisao:state.revisao,comando:'createShapes',args:[[{id:'shape:dev',type:'geo',x:0,y:0,text:'Vite funciona'}]]})
 assert.equal((await call('/api/v1/canvas/estado?alvo=sessao:dev-api')).formas.length,1)
 assert.ok(fs.existsSync(path.join(tmp,'sessoes/dev-api.tldr')))
 const desktop=await fetch(baseUrl+'/api/v1/operacoes/site/metricas',{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:'{"args":[]}'})
 assert.equal(desktop.status,503)
 assert.doesNotMatch(await page.locator('body').innerText(),/Something went wrong/)
})
